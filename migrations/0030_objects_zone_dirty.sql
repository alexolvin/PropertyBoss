-- C9: инкрементальный assign зон.
--
-- zone_dirty — координаты объекта изменились (enrich опубликовал новые)
-- или данные зон переимпортированы (zones.Import помечает всю страну) —
-- объект требует повторной привязки при следующем assign.
--
-- Без бэкап-фила: текущие zone_id валидны (зоны не менялись с последнего
-- глобального assign); объекты «есть координаты, нет зоны» попадают в
-- область действия assign через условие zone_id IS NULL.

ALTER TABLE objects ADD COLUMN zone_dirty BOOLEAN NOT NULL DEFAULT FALSE;
