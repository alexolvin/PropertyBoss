-- created_at — время постановки уведомления в очередь (этап 8).
-- Нужно для ретлимит-интервала повторных алертов (disk_low, ТЗ §3.2):
-- интервал считается от последней постановки, а не от отправки — если
-- отправка сломана (нет токена), очередь не должна заполняться
-- дублями при каждом проверочном прогоне. Аудит: видно, когда
-- событие было зафиксировано, а не только когда доставлено.
ALTER TABLE notifications ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now();
