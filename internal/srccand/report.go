// localNet — адреса петли, частных и CGNAT-сетей. В реестр, который лежит в git, они не попадают.
var localNet = regexp.MustCompile(`\b(?:127\.0\.0\.\d+|10\.\d{1,3}\.\d{1,3}\.\d{1,3}|192\.168\.\d{1,3}\.\d{1,3}|172\.(?:1[6-9]|2\d|3[0-1])\.\d{1,3}\.\d{1,3}|100\.(?:6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.\d{1,3}\.\d{1,3})(?::\d+)?\b`)

func redactLocal(s string) string {
	return localNet.ReplaceAllString(s, "local-address")
}

// WriteRegistry генерирует docs/sources/CZ_REGISTRY.md из БД. Ручная правка файла запрещена.
func WriteRegistry(path, commit, runID string, list []Candidate) error {
	if path == "" {
		path = "docs/sources/CZ_REGISTRY.md"
	}
	if err := os.MkdirAll("docs/sources", 0o755); err != nil {
		return err
	}
	now := time.Now().UTC().Format(time.RFC3339)
	var b bytes.Buffer
	fmt.Fprintf(&b, "<!-- generated by pb sources report; do not edit -->\n")
	fmt.Fprintf(&b, "# Реестр источников CZ\n\n")
	fmt.Fprintf(&b, "Сгенерировано: `%s`  \n", now)
	fmt.Fprintf(&b, "run_id: `%s`  \n", runID)
	fmt.Fprintf(&b, "commit: `%s`  \n", commit)
	fmt.Fprintf(&b, "кандидатов: %d\n\n", len(list))

	byClass := map[string]int{}
	for _, c := range list {
		byClass[c.Class]++
	}
	classes := make([]string, 0, len(byClass))
	for k := range byClass {
		classes = append(classes, k)
	}
	sort.Strings(classes)
	fmt.Fprintf(&b, "## Сводка классов\n\n| class | n |\n|---|---|\n")
	for _, k := range classes {
		fmt.Fprintf(&b, "| `%s` | %d |\n", k, byClass[k])
	}

	fmt.Fprintf(&b, "\n## Очередь этапа 2 (direct по убыванию reported_totals)\n\n")
	var direct []Candidate
	for _, c := range list {
		if c.Class == "direct" {
			direct = append(direct, c)
		}
	}
	sort.SliceStable(direct, func(i, j int) bool {
		if direct[i].Domain == "bezrealitky.cz" {
			return true
		}
		if direct[j].Domain == "bezrealitky.cz" {
			return false
		}
		return totalOf(direct[i]) > totalOf(direct[j])
	})
	if len(direct) == 0 {
		fmt.Fprintf(&b, "direct-источников нет.\n")
	} else {
		fmt.Fprintf(&b, "| # | domain | channel | reported_totals sum |\n|---|---|---|---|\n")
		for i, c := range direct {
			ch := ""
			if c.Channel != nil {
				ch = *c.Channel
			}
			fmt.Fprintf(&b, "| %d | `%s` | %s | %d |\n", i+1, c.Domain, ch, totalOf(c))
		}
	}

	fmt.Fprintf(&b, "\n## Кандидаты\n")
	for _, c := range list {
		fmt.Fprintf(&b, "\n### `%s`\n\n", c.Domain)
		fmt.Fprintf(&b, "- class: `%s`\n", c.Class)
		fmt.Fprintf(&b, "- via: `%s`\n", c.DiscoveredVia)
		if c.ClassReason != nil {
			fmt.Fprintf(&b, "- reason: %s\n", redactLocal(*c.ClassReason))
		}
		if c.Channel != nil {
			fmt.Fprintf(&b, "- channel: `%s`\n", *c.Channel)
		}
		if c.RobotsOK != nil {
			fmt.Fprintf(&b, "- robots_ok: %v\n", *c.RobotsOK)
		}
		if c.EvidencePath != nil {
			fmt.Fprintf(&b, "- evidence: `%s`\n", *c.EvidencePath)
		}
		if len(c.ProbeRunIDs) > 0 {
			fmt.Fprintf(&b, "- probe_run_ids: %s\n", strings.Join(c.ProbeRunIDs, ", "))
		}
		if c.ProbedAt != nil {
			fmt.Fprintf(&b, "- probed_at: %s\n", c.ProbedAt.UTC().Format(time.RFC3339))
		}
		if c.MirrorOf != nil {
			fmt.Fprintf(&b, "- mirror_of: `%s`\n", *c.MirrorOf)
		}
		if c.TosURL != nil {
			fmt.Fprintf(&b, "- tos_url: %s\n", *c.TosURL)
		}
		if c.TosExcerpt != nil {
			fmt.Fprintf(&b, "- tos_excerpt: %s\n", strconv.Quote(*c.TosExcerpt))
		}
		if len(c.ReportedTotals) > 0 {
			fmt.Fprintf(&b, "- reported_totals: `%s`\n", compactJSON(c.ReportedTotals))
		}
	}
	return os.WriteFile(path, b.Bytes(), 0o644)
}

func totalOf(c Candidate) int {
	if len(c.ReportedTotals) == 0 {
		return 0
	}
	var m map[string]any
	if err := json.Unmarshal(c.ReportedTotals, &m); err != nil {
		return 0
	}
	for _, k := range []string{"sum", "list_counter", "sitemap_loc"} {
		switch v := m[k].(type) {
		case float64:
			return int(v)
		case int:
			return v
		}
	}
	return 0
}

func compactJSON(b []byte) string {
	var buf bytes.Buffer
	if err := json.Compact(&buf, b); err != nil {
		return string(b)
	}
	s := buf.String()
	if len(s) > 400 {
		return s[:400] + "…"
	}
	return s
}
